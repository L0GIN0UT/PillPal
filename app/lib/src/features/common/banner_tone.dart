/// The look of a `PillPalBanner`.
enum BannerTone {
  /// `actionSoft` card: a hint or a note the user may act on.
  soft,

  /// Neutral `raised` card: information, never an error.
  info,

  /// `dangerSoft` card with a danger-ink icon: a blocking problem or a
  /// failure. "Missed" is not danger.
  danger,
}
