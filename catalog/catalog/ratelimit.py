"""Fixed-window rate limiting in Redis, per client IP and per ``X-Catalog-Install``.

Fails open: if Redis is unavailable the request is allowed and a warning is logged. The catalog
is public reference data; the limiter only blunts scraping and abuse.

Privacy: buckets are named by an HMAC of the IP or install id (keyed by a salt), never by the raw
value, and expire with their window. The raw values are used in memory only and never logged.
"""

from __future__ import annotations

import hashlib
import hmac
import re
import time
from collections.abc import Callable, Sequence
from typing import Any

from fastapi import Request
from redis.asyncio import Redis
from redis.exceptions import RedisError

from catalog.config import Settings
from catalog.errors import AppError
from catalog.observability import get_logger

INSTALL_HEADER = "X-Catalog-Install"
# A random id generated by the app; anything else is ignored (the IP bucket still applies).
_INSTALL_RE = re.compile(r"^[A-Za-z0-9_-]{16,64}$")
_BUCKET_DIGEST_LENGTH = 32

_log = get_logger("catalog.ratelimit")


class RateLimiter:
    def __init__(
        self,
        redis: Redis,
        settings: Settings,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        assert settings.rate_limit_salt is not None  # filled in by Settings  # noqa: S101
        self._redis = redis
        self._clock = clock
        # While now < this, Redis is considered down: skip it instead of waiting for a timeout.
        self._skip_redis_until = 0.0
        self._breaker_seconds = settings.rate_limit_unavailable_seconds
        self._salt = settings.rate_limit_salt.get_secret_value().encode()
        self._ip_limit = settings.rate_limit_ip_max
        self._install_limit = settings.rate_limit_install_max
        self._window = settings.rate_limit_window_seconds

    def _bucket(self, kind: str, value: str) -> str:
        digest = hmac.new(self._salt, f"{kind}|{value}".encode(), hashlib.sha256).hexdigest()
        return f"rl:{kind}:{digest[:_BUCKET_DIGEST_LENGTH]}"

    async def check(self, ip: str, install: str | None) -> None:
        """Count one request; raise 429 when a bucket is over its limit."""
        buckets: list[tuple[str, int]] = [(self._bucket("ip", ip), self._ip_limit)]
        if install is not None:
            buckets.append((self._bucket("install", install), self._install_limit))
        if self._clock() < self._skip_redis_until:
            return
        try:
            results = await self._count(buckets)
        except (RedisError, OSError):
            self._skip_redis_until = self._clock() + self._breaker_seconds
            _log.warning("rate_limiter_unavailable", retry_in_seconds=self._breaker_seconds)
            return
        for i, (_, limit) in enumerate(buckets):
            count, ttl = int(results[i * 3]), int(results[i * 3 + 2])
            if count > limit:
                _log.info("rate_limited")
                raise AppError(
                    429,
                    "rate_limited",
                    "Too many requests, try again later",
                    headers={"Retry-After": str(ttl if ttl > 0 else self._window)},
                )

    async def _count(self, buckets: Sequence[tuple[str, int]]) -> list[Any]:
        async with self._redis.pipeline(transaction=False) as pipe:
            for key, _ in buckets:
                pipe.incr(key)
                pipe.expire(key, self._window, nx=True)
                pipe.ttl(key)
            return list(await pipe.execute())


def _client_ip(request: Request) -> str:
    # Behind a reverse proxy run uvicorn with --proxy-headers/--forwarded-allow-ips.
    return request.client.host if request.client else "unknown"


def _install_id(request: Request) -> str | None:
    value = request.headers.get(INSTALL_HEADER)
    return value if value is not None and _INSTALL_RE.match(value) else None


async def rate_limited(request: Request) -> None:
    """Route dependency: ``dependencies=[Depends(rate_limited)]`` on public catalog routes."""
    limiter: RateLimiter = request.app.state.rate_limiter
    await limiter.check(_client_ip(request), _install_id(request))
