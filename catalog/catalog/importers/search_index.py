"""Search entries of a run (ADR 0012 section 5): rebuilt only for the entities the run changed,
inside the run's transaction. ``norm`` and ``tsv`` are generated by PostgreSQL."""

from __future__ import annotations

import re
from collections.abc import Iterable, Mapping
from typing import Any
from uuid import UUID

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from catalog.importers.upsert import chunks

_CYRILLIC = re.compile("[\u0400-\u04ff]")


def entry_language(value: str) -> str:
    """``ru`` for text with Cyrillic letters, else ``en``; brand names carry no language tag."""
    return "ru" if _CYRILLIC.search(value) else "en"


async def rebuild_entries(
    session: AsyncSession,
    kind: str,
    entries: Mapping[UUID, tuple[str, Iterable[tuple[str, str]]]],
) -> int:
    """Replace the entries of the given entities: ``{id: (market, {(lang, text), ...})}``."""
    if not entries:
        return 0
    ids = list(entries)
    await session.execute(
        text(
            "DELETE FROM catalog.search_entries WHERE entity_kind = :kind AND entity_id = ANY(:ids)"
        ),
        {"kind": kind, "ids": ids},
    )
    rows: list[dict[str, Any]] = [
        {"kind": kind, "id": entity_id, "market": market, "lang": lang, "text": value}
        for entity_id, (market, texts) in entries.items()
        for lang, value in sorted(set(texts))
        if value.strip()
    ]
    for batch in chunks(rows):
        await session.execute(
            text(
                "INSERT INTO catalog.search_entries (entity_kind, entity_id, market, lang, text) "
                "VALUES (:kind, :id, :market, :lang, :text) ON CONFLICT DO NOTHING"
            ),
            list(batch),
        )
    return len(ids)
