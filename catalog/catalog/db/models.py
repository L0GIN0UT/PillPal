"""Catalog tables (revisions c0002 to c0005). Public reference data only (ADR 0011, 0012).

The migrations are the source of truth for constraints; these definitions describe the same
columns for the importer's Core statements, and ``tests/importers/test_schema.py`` fails when
the two drift apart. ``norm`` and ``tsv`` of ``search_entries`` are generated by PostgreSQL and
are therefore not mapped as writable columns.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal
from typing import Any, cast

from sqlalchemy import (
    BigInteger,
    Boolean,
    Computed,
    DateTime,
    ForeignKey,
    Integer,
    MetaData,
    Numeric,
    String,
    Table,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, TSVECTOR, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

SCHEMA = "catalog"


class Base(DeclarativeBase):
    metadata = MetaData(schema=SCHEMA)


def _fk(target: str) -> ForeignKey:
    return ForeignKey(f"{SCHEMA}.{target}")


class Source(Base):
    __tablename__ = "sources"

    code: Mapped[str] = mapped_column(Text, primary_key=True)
    name: Mapped[str] = mapped_column(Text)
    license: Mapped[str] = mapped_column(Text)
    attribution: Mapped[str] = mapped_column(Text)
    url: Mapped[str] = mapped_column(Text)
    enabled: Mapped[bool] = mapped_column(Boolean, default=True)


class ImportRun(Base):
    __tablename__ = "import_runs"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    source: Mapped[str] = mapped_column(Text, _fk("sources.code"))
    source_version: Mapped[str | None] = mapped_column(Text)
    snapshot_sha256: Mapped[str] = mapped_column(String(64))
    status: Mapped[str] = mapped_column(Text)
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    counts: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default="{}")
    error_code: Mapped[str | None] = mapped_column(Text)


class Substance(Base):
    __tablename__ = "substances"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    source: Mapped[str] = mapped_column(Text, _fk("sources.code"))
    source_key: Mapped[str] = mapped_column(Text)
    market: Mapped[str] = mapped_column(Text)
    name_en: Mapped[str | None] = mapped_column(Text)
    name_ru: Mapped[str | None] = mapped_column(Text)
    withdrawn_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_run_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), _fk("import_runs.id"))


class SubstanceName(Base):
    __tablename__ = "substance_names"

    substance_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), _fk("substances.id"), primary_key=True
    )
    lang: Mapped[str] = mapped_column(Text, primary_key=True)
    name: Mapped[str] = mapped_column(Text, primary_key=True)
    source: Mapped[str] = mapped_column(Text, _fk("sources.code"))


class Composition(Base):
    __tablename__ = "compositions"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    source: Mapped[str] = mapped_column(Text, _fk("sources.code"))
    source_key: Mapped[str] = mapped_column(Text)
    market: Mapped[str] = mapped_column(Text)
    form_code: Mapped[str | None] = mapped_column(Text)
    form_name_en: Mapped[str | None] = mapped_column(Text)
    form_name_ru: Mapped[str | None] = mapped_column(Text)
    complete: Mapped[bool] = mapped_column(Boolean, default=False)
    identity_key: Mapped[str] = mapped_column(String(64))
    withdrawn_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_run_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), _fk("import_runs.id"))


class CompositionIngredient(Base):
    __tablename__ = "composition_ingredients"

    composition_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), _fk("compositions.id"), primary_key=True
    )
    substance_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), _fk("substances.id"), primary_key=True
    )
    strength_value: Mapped[Decimal | None] = mapped_column(Numeric)
    strength_unit: Mapped[str | None] = mapped_column(Text)
    per_value: Mapped[Decimal | None] = mapped_column(Numeric)
    per_unit: Mapped[str | None] = mapped_column(Text)


class Product(Base):
    __tablename__ = "products"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    source: Mapped[str] = mapped_column(Text, _fk("sources.code"))
    source_key: Mapped[str] = mapped_column(Text)
    market: Mapped[str] = mapped_column(Text)
    brand_name: Mapped[str] = mapped_column(Text)
    manufacturer: Mapped[str | None] = mapped_column(Text)
    country: Mapped[str | None] = mapped_column(Text)
    composition_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), _fk("compositions.id")
    )
    rx_status: Mapped[str | None] = mapped_column(Text)
    registration_number: Mapped[str | None] = mapped_column(Text)
    withdrawn_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_run_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), _fk("import_runs.id"))


class RecallFlag(Base):
    __tablename__ = "recall_flags"

    registration_number: Mapped[str] = mapped_column(Text, primary_key=True)
    series: Mapped[str] = mapped_column(Text, primary_key=True)
    reason_code: Mapped[str] = mapped_column(Text)
    source: Mapped[str] = mapped_column(Text, _fk("sources.code"), primary_key=True)
    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class Package(Base):
    __tablename__ = "packages"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    product_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), _fk("products.id"))
    source: Mapped[str] = mapped_column(Text, _fk("sources.code"))
    source_key: Mapped[str] = mapped_column(Text)
    description: Mapped[str | None] = mapped_column(Text)
    count: Mapped[Decimal | None] = mapped_column(Numeric)
    count_unit: Mapped[str | None] = mapped_column(Text)
    withdrawn_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_run_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), _fk("import_runs.id"))


class Gtin(Base):
    __tablename__ = "gtins"

    gtin: Mapped[str] = mapped_column(String(14), primary_key=True)
    source: Mapped[str] = mapped_column(Text, _fk("sources.code"), primary_key=True)
    package_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), _fk("packages.id"))
    origin: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    withdrawn_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_run_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), _fk("import_runs.id"))


class GtinLinkDecision(Base):
    """What the lookup needs of ADR 0014 section 4; written by the consensus code (4.7)."""

    __tablename__ = "gtin_link_decisions"

    gtin: Mapped[str] = mapped_column(String(14), primary_key=True)
    status: Mapped[str] = mapped_column(Text)
    product_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), _fk("products.id"))
    decided_by: Mapped[str] = mapped_column(Text)
    decided_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    reason_code: Mapped[str | None] = mapped_column(Text)


class SearchEntry(Base):
    __tablename__ = "search_entries"

    entity_kind: Mapped[str] = mapped_column(Text, primary_key=True)
    entity_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    market: Mapped[str] = mapped_column(Text)
    lang: Mapped[str] = mapped_column(Text, primary_key=True)
    text: Mapped[str] = mapped_column(Text, primary_key=True)
    norm: Mapped[str] = mapped_column(Text, Computed("catalog.search_norm(text)", persisted=True))
    tsv: Mapped[str] = mapped_column(
        TSVECTOR,
        Computed("to_tsvector('simple'::regconfig, catalog.search_norm(text))", persisted=True),
    )


class GtinLinkCandidate(Base):
    """A region's committed confirmation count for ``(gtin, product)`` (c0005, ADR 0014)."""

    __tablename__ = "gtin_link_candidates"

    region: Mapped[str] = mapped_column(Text, primary_key=True)
    gtin: Mapped[str] = mapped_column(String(14), primary_key=True)
    product_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), _fk("products.id"), primary_key=True
    )
    confirmations: Mapped[int] = mapped_column(Integer)


class GtinCandidateStaging(Base):
    """Pages of a snapshot that is not complete yet."""

    __tablename__ = "gtin_candidate_staging"

    region: Mapped[str] = mapped_column(Text, primary_key=True)
    generation: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    page: Mapped[int] = mapped_column(Integer)
    gtin: Mapped[str] = mapped_column(String(14), primary_key=True)
    product_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), _fk("products.id"), primary_key=True
    )
    confirmations: Mapped[int] = mapped_column(Integer)


class GtinIngestState(Base):
    __tablename__ = "gtin_ingest_state"

    region: Mapped[str] = mapped_column(Text, primary_key=True)
    committed_generation: Mapped[int] = mapped_column(BigInteger, server_default="0")
    committed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    staging_generation: Mapped[int | None] = mapped_column(BigInteger)
    staged_pages: Mapped[list[int]] = mapped_column(ARRAY(Integer), server_default="{}")


class AdminAudit(Base):
    """Who (a token label) did what to which GTIN. No personal data."""

    __tablename__ = "admin_audit"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    admin_name: Mapped[str] = mapped_column(Text)
    action: Mapped[str] = mapped_column(Text)
    gtin: Mapped[str | None] = mapped_column(String(14))
    product_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))
    region: Mapped[str | None] = mapped_column(Text)
    previous_status: Mapped[str | None] = mapped_column(Text)
    previous_product_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))


def table_of(model: type[Base]) -> Table:
    """The ``Table`` of a model, typed for Core statements."""
    return cast(Table, model.__table__)
